import fs from 'node:fs';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import type { Container } from '@azure/cosmos';
import { getFormSettingsContainer, getTasksContainer } from '../src/shared/infra/cosmos';
import {
  DEFAULT_FORM_SETTING_ID,
  type FormField,
  type FormRow,
  type FormSetting,
} from '../src/models/formSettingModel';
import { TASK_PRIORITIES, TASK_STATUSES, type Task } from '../src/models/taskModel';

const DEFAULT_ORGANIZATION_ID = '00000000-0000-0000-0000-000000000001';
const DAY_MS = 24 * 60 * 60 * 1000;
const SAMPLE_TITLES = [
  'Draft quarterly report',
  'Review pull request',
  'Fix login bug',
  'Prepare sprint planning',
  'Update API documentation',
  'Refactor task query layer',
  'Interview candidate',
  'Deploy staging build',
  'Write release notes',
  'Triage support tickets',
];
const SAMPLE_TAGS = ['backend', 'frontend', 'urgent', 'design', 'research', 'ops'];

function loadLocalSettings(): void {
  const settingsPath = path.resolve(process.cwd(), 'local.settings.json');
  if (!fs.existsSync(settingsPath)) {
    return;
  }
  const { Values } = JSON.parse(fs.readFileSync(settingsPath, 'utf8')) as {
    Values?: Record<string, string>;
  };
  for (const [key, value] of Object.entries(Values ?? {})) {
    process.env[key] ??= value;
  }
}

function isoDate(daysFromNow: number): string {
  return new Date(Date.now() + daysFromNow * DAY_MS).toISOString().slice(0, 10);
}

function isoDateTime(daysFromNow: number): string {
  return new Date(Date.now() + daysFromNow * DAY_MS).toISOString();
}

function field(
  id: string,
  type: FormField['type'],
  label: string,
  options: Partial<Pick<FormField, 'required' | 'disabled' | 'deletedAt'>> = {},
): FormField {
  return {
    id,
    type,
    label,
    required: options.required ?? false,
    disabled: options.disabled ?? false,
    deletedAt: options.deletedAt ?? null,
  };
}

function buildFormSetting(organizationId: string): FormSetting {
  const now = new Date().toISOString();
  const rows: FormRow[] = [
    {
      id: 'row-notes',
      fields: [field('note', 'text', 'Notes', { required: true }), field('contact_email', 'email', 'Contact email')],
    },
    {
      id: 'row-schedule',
      fields: [
        field('start_date', 'date', 'Start date'),
        field('remind_at', 'datetime', 'Remind at', { required: true }),
      ],
    },
    {
      id: 'row-extra',
      fields: [
        field('ref_code', 'text', 'Reference code', { disabled: true }),
        field('obsolete_field', 'text', 'Obsolete field', { deletedAt: now }),
      ],
    },
  ];
  return { id: DEFAULT_FORM_SETTING_ID, organizationId, rows, createdAt: now, updatedAt: now };
}

function buildSampleTask(organizationId: string, index: number): Task {
  const dueDate = new Date(Date.now() + ((index % 14) - 7) * DAY_MS);
  const customFields: Record<string, string> = {
    note: `Note for task ${index + 1}`,
    remind_at: isoDateTime((index % 7) - 3),
  };
  if (index % 4 !== 3) {
    customFields.contact_email = `user${index + 1}@example.com`;
    customFields.start_date = isoDate((index % 10) - 5);
  }

  return {
    id: randomUUID(),
    organizationId,
    title: `${SAMPLE_TITLES[index % SAMPLE_TITLES.length]} #${index + 1}`,
    description: `Sample task ${index + 1} generated by the seed script.`,
    dueDate: dueDate.toISOString(),
    priority: TASK_PRIORITIES[index % TASK_PRIORITIES.length],
    status: TASK_STATUSES[index % TASK_STATUSES.length],
    tags: [SAMPLE_TAGS[index % SAMPLE_TAGS.length], SAMPLE_TAGS[(index + 3) % SAMPLE_TAGS.length]],
    customFields,
    createdAt: new Date(Date.now() - index * 1000).toISOString(),
  };
}

function buildDesyncTasks(organizationId: string): Task[] {
  const specs: Array<{ title: string; description: string; customFields: Record<string, string> }> = [
    {
      title: 'Desync: unknown field',
      description: 'customFields contains legacy_id, which is not part of the form setting. The API drops it on read.',
      customFields: { note: 'Has a stale field value', remind_at: isoDateTime(1), legacy_id: 'abc-123' },
    },
    {
      title: 'Desync: wrong type',
      description: 'Values do not match their field types (email, date, datetime). Reads return them unchanged.',
      customFields: {
        note: 'Malformed values',
        remind_at: 'yesterday',
        contact_email: 'not-an-email',
        start_date: 'someday',
      },
    },
    {
      title: 'Desync: missing required',
      description: 'Missing note and remind_at, both required.',
      customFields: { contact_email: 'someone@example.com', start_date: isoDate(3) },
    },
    {
      title: 'Desync: disabled field',
      description: 'Has a value for ref_code, which is disabled. Shown read-only and dropped on save.',
      customFields: { note: 'Has a disabled field value', remind_at: isoDateTime(2), ref_code: 'LEGACY-001' },
    },
    {
      title: 'Desync: deleted field',
      description: 'Has a value for obsolete_field, which is soft-deleted. The API drops it on read.',
      customFields: { note: 'Has a deleted field value', remind_at: isoDateTime(4), obsolete_field: 'should be hidden' },
    },
  ];

  return specs.map((spec, index) => ({
    id: randomUUID(),
    organizationId,
    title: spec.title,
    description: spec.description,
    status: 'todo',
    priority: 'medium',
    customFields: spec.customFields,
    createdAt: new Date(Date.now() + (specs.length - index) * 1000).toISOString(),
  }));
}

async function resetTasks(container: Container, organizationId: string): Promise<number> {
  const { resources } = await container.items
    .query<{ id: string }>({
      query: 'SELECT c.id FROM c WHERE c.organizationId = @organizationId',
      parameters: [{ name: '@organizationId', value: organizationId }],
    })
    .fetchAll();

  await Promise.all(resources.map((item) => container.item(item.id, organizationId).delete()));
  return resources.length;
}

async function main(): Promise<void> {
  loadLocalSettings();

  const organizationId = process.env.SEED_ORGANIZATION_ID ?? DEFAULT_ORGANIZATION_ID;
  const count = Number(process.env.SEED_COUNT ?? 40);
  const tasksContainer = await getTasksContainer();
  const formSettingsContainer = await getFormSettingsContainer();

  const removed = await resetTasks(tasksContainer, organizationId);

  const setting = buildFormSetting(organizationId);
  await formSettingsContainer.items.upsert(setting);

  const sampleTasks = Array.from({ length: count }, (_, index) => buildSampleTask(organizationId, index));
  const desyncTasks = buildDesyncTasks(organizationId);
  await Promise.all([...sampleTasks, ...desyncTasks].map((task) => tasksContainer.items.create(task)));

  const activeFields = setting.rows.flatMap((row) => row.fields).filter((f) => !f.deletedAt);

  console.log(`Reset ${removed} existing task(s) for organizationId ${organizationId}`);
  console.log(`Seeded ${sampleTasks.length + desyncTasks.length} tasks (${sampleTasks.length} sample + ${desyncTasks.length} desync)`);
  console.log(`Form setting "${DEFAULT_FORM_SETTING_ID}" active fields:`);
  for (const f of activeFields) {
    const flags = [f.required ? 'required' : '', f.disabled ? 'disabled' : ''].filter(Boolean).join(', ');
    console.log(`  - ${f.id} (${f.type})${flags ? ` [${flags}]` : ''}`);
  }
  console.log('Desync examples (top of the list):');
  for (const task of desyncTasks) {
    console.log(`  - ${task.title}`);
  }
}

main().catch((error) => {
  console.error('Seeding failed:', error);
  process.exitCode = 1;
});
