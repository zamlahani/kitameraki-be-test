import fs from 'node:fs';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import { getTasksContainer } from '../src/shared/cosmos';
import { TASK_PRIORITIES, TASK_STATUSES, type Task } from '../src/models/taskModel';

const DEFAULT_ORGANIZATION_ID = '00000000-0000-0000-0000-000000000001';
const SAMPLE_TITLES = [
  'Draft quarterly report',
  'Review pull request',
  'Fix login bug',
  'Prepare sprint planning',
  'Update API documentation',
  'Refactor task query layer',
  'Interview candidate',
  'Deploy staging build',
  'Write release notes',
  'Triage support tickets',
];
const SAMPLE_TAGS = ['backend', 'frontend', 'urgent', 'design', 'research', 'ops'];

function loadLocalSettings(): void {
  const settingsPath = path.resolve(process.cwd(), 'local.settings.json');
  if (!fs.existsSync(settingsPath)) {
    return;
  }
  const { Values } = JSON.parse(fs.readFileSync(settingsPath, 'utf8')) as {
    Values?: Record<string, string>;
  };
  for (const [key, value] of Object.entries(Values ?? {})) {
    process.env[key] ??= value;
  }
}

function buildTask(organizationId: string, index: number): Task {
  const dueDate = new Date();
  dueDate.setDate(dueDate.getDate() + (index % 14) - 7);

  const createdAt = new Date(Date.now() - index * 1000).toISOString();

  return {
    id: randomUUID(),
    organizationId,
    title: `${SAMPLE_TITLES[index % SAMPLE_TITLES.length]} #${index + 1}`,
    description: `Sample task ${index + 1} generated by the seed script.`,
    dueDate: dueDate.toISOString(),
    priority: TASK_PRIORITIES[index % TASK_PRIORITIES.length],
    status: TASK_STATUSES[index % TASK_STATUSES.length],
    tags: [SAMPLE_TAGS[index % SAMPLE_TAGS.length], SAMPLE_TAGS[(index + 3) % SAMPLE_TAGS.length]],
    createdAt,
  };
}

async function main(): Promise<void> {
  loadLocalSettings();

  const organizationId = process.env.SEED_ORGANIZATION_ID ?? DEFAULT_ORGANIZATION_ID;
  const count = Number(process.env.SEED_COUNT ?? 40);
  const container = await getTasksContainer();

  await Promise.all(
    Array.from({ length: count }, (_, index) => container.items.create(buildTask(organizationId, index))),
  );

  console.log(`Seeded ${count} tasks for organizationId ${organizationId}`);
}

main().catch((error) => {
  console.error('Seeding failed:', error);
  process.exitCode = 1;
});
